"""Build an energy training set from a trained density-matrix model.

The energy model's input is not a reference density matrix but a **predicted**
one, errors and all -- that is the whole point, since its job is to say what a
given prediction is worth. So the training set has to be generated by running a
specific RDM checkpoint over the data.

For each molecule this writes the predicted matrix and the targets::

    rdm_pred        (n_ao, n_ao)  the model's density matrix, float32
    e_ref           scalar        the stored reference energy
    e_functional    scalar        E[rdm_pred] from pyscf, DFT only
    delta           scalar        e_ref - e_functional, DFT only

**Two target choices, and the dataset carries what both need.** On a DFT set the
energy of the predicted matrix is computable, so the useful target is the
*residual* ``e_ref - e_functional``: evaluate the functional at inference and add
the learned correction. On MP2 no such baseline exists -- the total energy is not
a functional of the 1-RDM -- so the target is ``e_ref`` itself and the model has
to carry the whole range. Which one is used is a config choice
(``target_mode``), not a property of the file.

Usage::

    .venv/bin/python boa/make_energy_dataset.py \\
        --run  <rdm run directory> \\
        --out  $BOA_DATA/df_db_pbe_energy_run100 \\
        --splits train validation test

The output directory is named after the run that produced it on purpose: a
predicted density matrix is only meaningful together with the checkpoint that
produced it, and two runs' outputs must never be mixed.
"""

from __future__ import annotations

import argparse
import json
import logging
import os
from pathlib import Path

# Before numpy/torch/pyscf: they size their thread pools at load time, and
# nothing afterwards shrinks a pool that is already up. Uncapped, pyscf takes all
# 128 cores here and runs *twice as slow* as at 32; see boa/cpu_limit.py.
from boa.cpu_limit import DEFAULT_CPUS, limit_from_argv

_CPUS = limit_from_argv()

import h5py  # noqa: E402
import numpy as np  # noqa: E402
import torch  # noqa: E402

logging.basicConfig(level=logging.INFO, format="%(message)s")
log = logging.getLogger("make_energy_dataset")


def parse_args():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--run", required=True, type=Path, help="trained RDM run directory")
    p.add_argument("--out", required=True, type=Path, help="output directory")
    p.add_argument(
        "--splits", nargs="+", default=["train", "validation", "test"],
        choices=["train", "validation", "test"],
    )
    p.add_argument("--ckpt", type=Path, default=None)
    p.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    p.add_argument("--limit", type=int, default=0,
               help="stop after N molecules *per split* (0 = all)")
    p.add_argument(
        "--shard", type=int, default=0,
        help="which shard this process handles, 0-based",
    )
    p.add_argument(
        "--num-shards", type=int, default=1,
        help="split each split's molecules across this many processes. Each shard "
             "takes indices shard::num_shards, so the work is interleaved and "
             "therefore balanced by molecule size rather than by position.",
    )
    p.add_argument(
        "--merge-index", action="store_true",
        help="combine the per-shard index files into datasplits.json and exit. Run "
             "once after all shards finish.",
    )
    p.add_argument(
        "--cpus", type=int, default=DEFAULT_CPUS,
        help="OpenMP/BLAS threads (0 = leave the environment alone). Read before "
             "argparse so it takes effect; declared here for --help and validation. "
             "For throughput over many molecules prefer several single-threaded "
             "processes over one wide one -- parallel efficiency collapses long "
             "before the core count does.",
    )
    p.add_argument(
        "--no-energy",
        action="store_true",
        help="skip the pyscf energy of the prediction. Implied for a correlated "
             "(MP2) source, where it is not a functional of the 1-RDM.",
    )
    return p.parse_args()


def write_index(out: Path) -> None:
    """Combine the per-shard index files into the split file the loader reads.

    `DataModule` applies a split as integer indices, and `EnergyDataset` orders
    its molecules by sorted filename, so ids are converted against exactly that
    ordering -- which is only knowable once every shard has finished. The ids are
    kept alongside because an index is meaningless if the directory is later
    regenerated with different membership.
    """
    merged: dict[str, list[str]] = {}
    shards = sorted(out.glob("_index_shard*.json"))
    if not shards:
        raise FileNotFoundError(f"no _index_shard*.json in {out}")
    for path in shards:
        for split, ids in json.loads(path.read_text()).items():
            merged.setdefault(split, []).extend(ids)
    order = {m: i for i, m in enumerate(sorted(i for v in merged.values() for i in v))}
    (out / "datasplits.json").write_text(
        json.dumps({k: sorted(order[i] for i in v) for k, v in merged.items()})
    )
    (out / "datasplits_ids.json").write_text(json.dumps(merged))
    log.info(
        f"merged {len(shards)} shards -> "
        + ", ".join(f"{k} {len(v)}" for k, v in merged.items())
    )


def main():
    args = parse_args()
    if args.merge_index:
        write_index(args.out)
        return
    import hydra
    from dotenv import load_dotenv
    from omegaconf import OmegaConf

    from boa.eval_energy import pick_checkpoint
    from boa.model.properties import total_energy

    repo = Path(__file__).resolve().parents[1]
    os.environ.setdefault("PROJECT_ROOT", str(repo))
    load_dotenv(repo / ".env")
    OmegaConf.register_new_resolver(
        "hydra",
        lambda key: {"runtime.output_dir": str(args.run), "runtime.cwd": os.getcwd()}.get(key, ""),
        replace=True,
    )

    cfg = OmegaConf.load(args.run / "config.yaml")
    OmegaConf.resolve(cfg)
    ds_cfg = cfg.data.datamodule.dataset
    props = list(ds_cfg.get("extra_props", []) or [])
    if "energy" not in props:
        ds_cfg.extra_props = props + ["energy"]

    datamodule = hydra.utils.instantiate(cfg.data.datamodule, _recursive_=False)
    datamodule.setup("fit")
    model = hydra.utils.instantiate(
        cfg.model, train=cfg, _recursive_=False, metadata=getattr(datamodule, "metadata", None)
    )
    ckpt = args.ckpt or pick_checkpoint(args.run)
    log.info(f"checkpoint: {ckpt}")
    log.info(f"thread cap: {_CPUS}, shard {args.shard + 1}/{args.num_shards}")
    model.load_state_dict(torch.load(ckpt, map_location="cpu", weights_only=False)["state_dict"])
    model.eval().to(args.device)

    basis = cfg.model.get("dft_basis_set", "6-31g*")
    xc = cfg.model.get("energy_xc", "lda,vwn_rpa")
    # A correlated source has no energy functional of the 1-RDM to evaluate.
    source = str(cfg.data.get("dataset_name", ""))
    correlated = "mp2" in source.lower()
    want_energy = not args.no_energy and not correlated
    log.info(
        f"source {source}, basis {basis}, xc {xc}; "
        f"{'computing' if want_energy else 'NOT computing'} E[rdm_pred]"
        + (" (correlated source: the MP2 energy is not a 1-RDM functional)" if correlated else "")
    )

    args.out.mkdir(parents=True, exist_ok=True)
    if not 0 <= args.shard < args.num_shards:
        raise SystemExit(f"--shard {args.shard} out of range for {args.num_shards} shards")

    datasets = {
        "train": datamodule.train_dataset,
        "validation": datamodule.val_dataset,
        "test": datamodule.test_dataset,
    }

    def loader_for(split: str):
        """This shard's slice of a split, as a loader.

        Sharded with a `Subset` rather than by skipping batches: a skipped batch
        still runs its transforms in the dataloader workers, so N shards would
        pay N times for the graph construction of every molecule. Slicing the
        dataset means each shard only ever materialises its own.
        """
        from torch.utils.data import Subset

        dataset = datasets[split]
        if args.num_shards > 1:
            dataset = Subset(dataset, list(range(args.shard, len(dataset), args.num_shards)))
        return datamodule._dataloader(
            dataset, False, datamodule.batch_size.val, datamodule.num_workers.val
        )

    loaders = {split: (lambda s=split: loader_for(s)) for split in datasets}
    index: dict[str, list[str]] = {}
    written = 0

    with torch.no_grad():
        for split in args.splits:
            ids: list[str] = []
            for batch in loaders[split]():
                if args.limit and len(ids) >= args.limit:
                    break
                batch = batch.to(args.device)
                _, pred, _, ao_mask = model(batch)
                e_ref_all = getattr(batch, "energy", None)
                for i in range(pred.shape[0]):
                    if args.limit and len(ids) >= args.limit:
                        break
                    mol_id, z, xyz = model._molecule(batch, i)
                    n_ao = int(ao_mask[i].sum())
                    dm = pred[i, :n_ao, :n_ao].float().cpu().numpy()
                    dm = 0.5 * (dm + dm.T)
                    row = {"rdm_pred": dm}
                    if e_ref_all is not None:
                        row["e_ref"] = float(e_ref_all.reshape(-1)[i])
                    if want_energy and "e_ref" in row:
                        try:
                            e_fun = total_energy(
                                z.numpy(), xyz.numpy(), dm, basis=basis, xc=xc
                            )
                            row["e_functional"] = e_fun
                            row["delta"] = row["e_ref"] - e_fun
                        except Exception as exc:
                            log.warning(f"{mol_id}: energy failed ({exc}); no delta stored")
                    with h5py.File(args.out / f"{mol_id}.hdf5", "w") as h5:
                        for k, v in row.items():
                            h5.create_dataset(k, data=np.asarray(v))
                        h5.attrs["source_id"] = mol_id
                        h5.attrs["source_dataset"] = source
                        h5.attrs["rdm_run"] = args.run.name
                    ids.append(mol_id)
                    written += 1
                    if written % 200 == 0:
                        log.info(f"  {written} molecules")
            index[split] = ids
            log.info(f"{split}: {len(ids)} molecules")

    # The split travels with the data: these predictions came from a model that
    # was trained on this split, so reusing its train molecules to *validate* the
    # energy model would be a leak the source dataset's own split cannot prevent.
    #
    # `DataModule` applies a split as integer indices, and `EnergyDataset` orders
    # its molecules by sorted filename, so the ids are converted against exactly
    # that ordering. The ids are kept alongside because an index is meaningless
    # if the directory is ever regenerated with a different membership.
    # One index file per shard; `--merge-index` combines them once all are done.
    # A shard cannot write datasplits.json itself: the indices depend on the final
    # membership of the directory, which no single shard knows.
    (args.out / f"_index_shard{args.shard:03d}.json").write_text(json.dumps(index))
    if args.num_shards == 1:
        write_index(args.out)
    (args.out / "provenance.json").write_text(json.dumps({
        "rdm_run": str(args.run),
        "checkpoint": str(ckpt),
        "source_dataset": source,
        "basis": basis,
        "xc": xc,
        "energy_of_prediction": want_energy,
        "correlated_source": correlated,
    }, indent=2))
    log.info(f"wrote {written} molecules to {args.out}")


if __name__ == "__main__":
    main()
